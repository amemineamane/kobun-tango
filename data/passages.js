/* =====================================================================
 * data/passages.js — 教材（文章）と現代語訳、その文章で覚える語
 * ---------------------------------------------------------------------
 * 【役割】
 *   中学・高校の教科書に定番として載る古典教材を「文章のまとまり」で持つ。
 *     ・教科書（#/textbook）／文章詳細（#/passage/:id）
 *     ・原文と現代語訳の段落対応表示
 *     ・原文中の重要語ハイライト → タップで語義ポップアップ
 *     ・「この文章の単語で学習／クイズ」のデッキ
 *   がこの 1 ファイルから生成される。
 *
 * 【他のデータとの関係】
 *   passages.js  … 教材単位（数段落）。原文・現代語訳・その文章で覚える語。
 *   data/tokens/<id>.js … その原文の **全文の品詞分解**（1 文章 1 ファイル）。
 *                 段落内の s を連結すると paragraphs[i].text と一字一句一致する。
 *                 これがあると、文章ページで原文のどの語もタップできる。
 *                 書き方は docs/tokens-guide.md。検証は tools/validate-tokens.mjs。
 *   examples.js  … 旧「品詞分解つき例文」。教材の原文そのものに品詞分解が
 *                 付いたので役目を終えつつある（DESIGN.md 5.2 の経緯を参照）。
 *
 * 【フィールド】
 *   id           文字列の安定ID。"作品id-教材の短い名" で付ける（URL になる）。
 *   workId       data/works.js の id
 *   title        教科書での教材名（「春はあけぼの」「仁和寺にある法師」）
 *   section      段・巻など出典の位置（任意）
 *   grade        教科書で扱われる学年の目安の配列（任意）例 ["中2","高校"]（高校は科目・学年が教科書により異なるため学年を分けない）
 *   paragraphs   段落の配列。1 段落 = { text（原文）, translation（現代語訳）}
 *                長い教材は有名部分を抜粋し、省いた箇所は本文中に「（中略）」と書く。
 *   vocab        この文章で覚える語の配列（下記）
 *   note         教材全体への注記。**自信のない箇所は「要確認: …」と書く**
 *   exam         大学入学共通テスト・センター試験（国語・古文）の出典から採った教材に
 *                付ける（任意）。{ year: 2022, test: '共通テスト' } の形。
 *                この文章が出題そのものの箇所か、同じ出題作品の別の場面かは
 *                note に書き分ける。設問・注・試験の訳は載せない（入試センターの著作物）。
 *                grade は ['入試'] とする。出典の裏取りは docs/exam-sources.md。
 *
 * 【vocab の 1 要素】
 *   surface      原文に出てくる形。**paragraphs[].text の中に必ず現れること**
 *                （tools/validate.mjs がこの出現をチェックする）
 *                この文字列が原文中でハイライトされ、タップで語義が出る。
 *                1 文字だけの surface は別語の一部に当たってしまうので避ける。
 *   wordId       330 語にある語なら data/words.js の id。無ければ書かない
 *   meaningIndex wordId がある場合、その文脈での語義の添字（words[].meanings の index）
 *   meaning      wordId が無い語（＝文章固有語）の語義。**wordId が無いなら必須**
 *   pos          wordId が無い語の品詞（クイズの誤答選びに使う）
 *   base         辞書形（任意）。ポップアップに「辞書形：〜」と出る
 *   note         注記（任意）
 *
 *   ※ 同じ wordId を 1 つの文章に 2 回書かないこと（validate が弾く）。
 *     同じ語の別の活用形も出てくる場合は note に書き添える。
 *
 * 【学習履歴のキー】
 *   wordId のある語 … その wordId（数値）。単語一覧・単語詳細と履歴を共有する。
 *   文章固有語     … "p:<passageId>:<vocab の添字>" という文字列キー。
 *   vocab の並び順を変えると固有語の履歴がずれるので、**途中に挿入せず末尾に足す**。
 *
 * 【文章を足すには】
 *   1. works.js にその作品があるか確認（無ければ先に足す）。
 *   2. この配列に 1 件足す。id は "作品id-短い名"（後から変えない）。
 *   3. paragraphs に原文と訳を段落ごとに書く。原文の正確さを最優先し、
 *      自信のない箇所は note に「要確認: …」と明記する。
 *   4. vocab に、その文章に出てくる 330 語（活用形も見て拾う）と、
 *      教科書で脚注になる文章固有語 3〜10 語を書く。
 *   5. node tools/validate.mjs でエラー 0 を確認。
 *   6. コードの変更は不要。教科書・作品ページ・フィルタに自動で出る。
 *
 * ※ 原文は一般的な教科書本文（伊勢物語＝定家本系、枕草子＝三巻本、方丈記＝大福光寺本 など）
 *   に拠り、Wikisource 日本語版・国立国会図書館デジタルコレクション・大学公開テキスト等と
 *   照合した（**一次校閲済。docs/verification.md 参照**）。底本による異同は各 note に
 *   「底本異同: …」として残してある。
 *   **現代語訳はこのアプリのために書き起こしたもの**で、
 *   教科書や市販の訳の引き写しではない。
 * ===================================================================== */
