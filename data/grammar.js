/* =====================================================================
 * data/grammar.js — 古典文法のデータ（助動詞・助詞・敬語・活用・識別）
 * ---------------------------------------------------------------------
 * 高校古典文法の標準的な内容を、画面が読める形にまとめたもの。
 * words.js / passages.js / tokens/*.js とは **独立したファイル**で、
 * 語（wordId）との紐づけと用例（コーパス）との紐づけは
 * どちらも「id」と「match 規則」だけで行う（DESIGN.md 5.4 の流儀）。
 *
 * ┌─────────────────────────────────────────────────────────────────┐
 * │ window.KOBUN.grammar = {                                       │
 * │   auxiliaries: [ AUX, … ]      助動詞 29                        │
 * │   particles:   [ PARTICLE, … ] 助詞 53                          │
 * │   kakari:      { rows, notes } 係り結びの表                      │
 * │   keigo:       { intro, groups, words, notes }  敬語             │
 * │   conjugation: { groups, tips } 動詞・形容詞・形容動詞の活用表     │
 * │   identification: [ IDENT, … ] 識別 13                          │
 * │ }                                                               │
 * └─────────────────────────────────────────────────────────────────┘
 *
 * 【共通のキー】
 *   id      … URL になる（#/grammar/aux/nu）。**後から変えない**。
 *             カテゴリをまたいで重複させない（索引が 1 つの Map なので）。
 *   name    … 見出し（「ぬ」「なり」）
 *   kind    … 分類（「完了」「打消」「格助詞」…）。一覧のグループ見出しに使う
 *   attach  … 接続（「連用形」「終止形（ラ変は連体形）」「体言・連体形」…）
 *   conj    … 活用の型（「ナ変型」「形容詞型」…。docs/tokens-guide.md §4 の表記）
 *   table   … 活用表。**必ず 6 要素**（未然・連用・終止・連体・已然・命令）。
 *             無い形は '○'。2 形あるものは 'ず／ざら' のように「／」で並べる
 *   meanings… [{ label: '完了', gloss: '〜た・〜てしまった', how: '見分け方',
 *               alias: ['確述'] }]
 *             label は品詞分解の m の「（　）」の中身と揃える（用例の抽出に効く）。
 *             品詞分解側が別の言い方をしている用法は alias に並べる
 *             （例：強意＝確述、順接確定条件＝順接確定・原因）。
 *             ドリルの「意味当て」は label／alias でトークンを分類する
 *   tips    … 識別・用法の要点（1〜3 文）
 *   note    … 諸説があるとき・流儀が分かれるときの注記（任意）
 *   related … 関連する識別ページの id（任意。配列）
 *   match   … 品詞分解トークン（data/tokens/*.js）との対応規則。§下記
 *
 * 【match 規則】
 *   { s, sEnd, b, p, c, f, m } のうち書いたキーだけを見る（書かないキーは無条件一致）。
 *     s/b/p/c/f … 完全一致（配列を書けばどれかに一致）
 *     sEnd      … 表層形の**末尾一致**（活用語尾だけを問題にしたいとき。
 *                 例：形容動詞のうち字面が「なり」で終わるものだけ）
 *     m         … **前方一致**。'完了' と書けば m が '（完了）…' で始まるものに当たる
 *                 （tokens-guide の「m は用法を（　）で頭に付ける」に合わせてある）。
 *                 '（完了）' と括弧ごと書いてもよい。'伝聞' は '（伝聞推定）…' にも当たる
 *   複数の書き方がある語は **規則の配列**にする（例「らし」は b が 'らし' と 'けらし'）。
 *   js/data-index.js の index.grammarExamples() がこの規則でコーパスを走査し、
 *   index.grammarOfToken() が逆にトークンから文法エントリを引く。
 *   規則が 1 件もヒットしない（コーパスに用例が無い）ことは異常ではない
 *   ＝ tools/validate-grammar.mjs は **警告**として出す。
 *
 * 【同形異義の扱い】
 *   「なり」（断定／伝聞推定）「たり」（完了・存続／断定）のように、
 *   同じ字面で別の助動詞のものは **別エントリ**にして m と conj で書き分ける。
 *   一方「る／らる」の受身・尊敬・自発・可能のように 1 語が複数の意味を持つものは
 *   **1 エントリの meanings に並べる**。
 *   「ぬ」は完了の助動詞（b: 'ぬ'）だけをここに置き、打消「ず」の連体形「ぬ」は
 *   b が 'ず' なので **「ず」のエントリ側**に含まれる（識別は identification の 'id-nu-ne'）。
 *
 * 【用例（example）を書かない理由】
 *   用例は data/tokens/*.js（教材の全文品詞分解）から自動抽出する。
 *   手で書くと原文の裏取りが二重になり、教材が増えても増えない。
 *   そのため各エントリに example は持たせない。
 *
 * 出典・校閲: 高校古典文法の標準的な整理（学校文法）に拠る。
 *   諸説あるところは note に書いた。**サンプル・要校閲**。
 * ===================================================================== */
